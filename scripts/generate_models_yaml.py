"""Write the pose of every model of a world into a YAML file in config/.

The grouped models (building, storage and furniture) are one entry each. Usage:

    python3 scripts/generate_models_yaml.py                     # every world in worlds/
    python3 scripts/generate_models_yaml.py large_warehouse_world.sdf
"""

import argparse
from pathlib import Path
from urllib.parse import unquote
import xml.etree.ElementTree as ET

PACKAGE_DIR = Path(__file__).resolve().parent.parent
WORLDS_DIR = PACKAGE_DIR / 'worlds'
CONFIG_DIR = PACKAGE_DIR / 'config'


def model_name(uri):
    """Model name of an include URI: model://<name> or a Fuel URL."""
    if uri.startswith('model://'):
        return uri[len('model://'):].strip('/')
    return unquote(uri.rstrip('/').split('/')[-1])


def read_models(world_file):
    """Return (world name, [(name, model, pose)]) of the includes of a world."""
    world = ET.parse(world_file).getroot().find('world')
    models = []
    for include in world.findall('include'):
        model = model_name(include.findtext('uri', '').strip())
        name = (include.findtext('name') or model).strip()
        pose = [float(v) for v in (include.findtext('pose') or '0 0 0 0 0 0').split()]
        models.append((name, model, pose + [0.0] * (6 - len(pose))))
    return world.get('name'), models


def write_yaml(world_name, world_file, models, output):
    lines = [
        f'# Models of the world {world_name} (generated by scripts/{Path(__file__).name})',
        f'# Source: worlds/{world_file.name}. Grouped models are one entry each.',
        '# Poses are in the world frame: x, y, z in meters and roll, pitch, yaw in radians.',
        f'world: {world_name}',
        f'count: {len(models)}',
        'models:',
    ]
    for name, model, (x, y, z, roll, pitch, yaw) in models:
        lines += [
            f'  - name: {name}',
            f'    model: {model}',
            f'    pose: {{x: {x:g}, y: {y:g}, z: {z:g}, roll: {roll:g}, pitch: {pitch:g}, yaw: {yaw:g}}}',
        ]
    output.write_text('\n'.join(lines) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('worlds', nargs='*',
                        help='world files in worlds/ (default: all of them)')
    args = parser.parse_args()

    world_files = ([WORLDS_DIR / w for w in args.worlds] if args.worlds
                   else sorted(WORLDS_DIR.glob('*.sdf')))
    CONFIG_DIR.mkdir(exist_ok=True)
    for world_file in world_files:
        world_name, models = read_models(world_file)
        output = CONFIG_DIR / f'{world_name}_models.yaml'
        write_yaml(world_name, world_file, models, output)
        print(f'{output.relative_to(PACKAGE_DIR)}: {len(models)} models')


if __name__ == '__main__':
    main()
