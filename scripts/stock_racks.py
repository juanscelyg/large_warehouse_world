"""
Fill the floor level of every Warehouse A rack with packages (a static Gazebo model).

Reads the rack poses (ShelfF visuals) from large_warehouse_world's
warehouse_a_storage model and places one package (of several sizes) in most
bays between the rack legs, on the floor and close to the aisle side, so a low
lidar sees them. One visual per package: the lidar renders the whole scene and
the real time factor drops with the number of visuals. Deterministic (fixed
seed). The output model uses world coordinates:
worlds/large_warehouse_world.sdf includes it at the origin.
"""

import argparse
import math
import pathlib
import random
import re

SHELF_MESH = 'aws_robomaker_warehouse_ShelfF_01_visual.DAE'
# Bays between the rack legs, along the rack (local y, m).
BAYS = [(-8.85, -4.65), (-4.3, -0.25), (0.1, 4.25), (4.65, 8.85)]
FRONT_X = -1.0  # aisle side of a rack (local x)
DEPTH = 2.0  # usable depth from the front (m)

# name: (size along the rack, depth, mesh, scale, yaw that puts the mesh's long side
# along the rack).
PACKAGES = {
    'box_pile_a': (2.14, 1.98, 'model://box_pile_a/meshes/aws_robomaker_warehouse_ClutteringA_01_visual.DAE',
                   '', math.pi / 2),
    'box_pile_c': (2.04, 1.76, 'model://box_pile_c/meshes/aws_robomaker_warehouse_ClutteringC_01_visual.DAE',
                   '', 0.0),
    'crate_stack': (1.22, 0.94, 'model://crate_stack/meshes/aws_robomaker_warehouse_Bucket_01_visual.DAE',
                    '', 0.0),
    # A cardboard box stretched to 0.6 m tall: a plain one (0.3 m) is below the lidar (~0.38 m).
    'cardboard_box': (0.5, 0.4, 'model://cardboard_box/meshes/cardboard_box.dae',
                      '<scale>1.25931896 1.007455168 1.511182752</scale>', math.pi / 2),
}
WEIGHTS = {'box_pile_a': 2, 'box_pile_c': 2, 'crate_stack': 3, 'cardboard_box': 3}


def racks(storage_sdf):
    pattern = re.compile(
        r'<pose>([-\d.e]+) ([-\d.e]+) [-\d.e]+ [-\d.e]+ [-\d.e]+ ([-\d.e]+)</pose>'
        r'<geometry>\s*<mesh>\s*<uri>[^<]*' + re.escape(SHELF_MESH))
    return [tuple(map(float, m.groups())) for m in pattern.finditer(storage_sdf.read_text())]


def main():
    ap = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    ap.add_argument('storage_sdf', type=pathlib.Path,
                    help="large_warehouse_world's models/warehouse_a_storage/model.sdf")
    ap.add_argument('--output', required=True, type=pathlib.Path, help='model directory to write')
    ap.add_argument('--seed', type=int, default=7)
    ap.add_argument('--empty-bay', type=float, default=0.25, help='probability of an empty bay')
    args = ap.parse_args()

    rng = random.Random(args.seed)
    names = list(WEIGHTS)
    visuals = []
    shelves = racks(args.storage_sdf)
    for rx, ry, ryaw in shelves:
        c, s = math.cos(ryaw), math.sin(ryaw)
        for y0, y1 in BAYS:
            if rng.random() < args.empty_bay:
                continue
            name = rng.choices(names, weights=[WEIGHTS[n] for n in names])[0]
            length, depth, uri, scale, mesh_yaw = PACKAGES[name]
            lx = FRONT_X + depth / 2.0 + rng.uniform(0.0, max(0.0, DEPTH - depth) * 0.3)
            ly = rng.uniform(y0 + length / 2.0, y1 - length / 2.0)
            wx, wy = rx + c * lx - s * ly, ry + s * lx + c * ly
            yaw = ryaw + mesh_yaw + rng.choice((0.0, math.pi))
            visuals.append(
                f'      <visual name="{name}_{len(visuals):04d}">'
                f'<pose>{wx:.3f} {wy:.3f} 0 0 0 {yaw:.4f}</pose>'
                f'<geometry><mesh><uri>{uri}</uri>{scale}</mesh></geometry></visual>')

    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / 'model.config').write_text(
        '<?xml version="1.0"?>\n<model>\n  <name>warehouse_a_floor_stock</name>\n'
        '  <version>1.0</version>\n  <sdf version="1.9">model.sdf</sdf>\n'
        '  <description>Packages on the floor level of the Warehouse A racks of '
        'large_warehouse_world (generated by scripts/stock_racks.py).</description>\n</model>\n')
    (args.output / 'model.sdf').write_text(
        '<?xml version="1.0"?>\n<!-- Generated by scripts/stock_racks.py: do not edit by hand. -->\n'
        '<sdf version="1.9">\n  <model name="warehouse_a_floor_stock">\n'
        '    <static>true</static>\n    <link name="packages">\n'
        + '\n'.join(visuals) + '\n    </link>\n  </model>\n</sdf>\n')
    print(f'{len(visuals)} packages in {len(shelves)} racks')


if __name__ == '__main__':
    main()
